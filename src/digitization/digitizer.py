from pixel_grid import*
from charge import*
from readout import*

import numpy as np

class Digitizer:
    '''
    @brief class that digitizes all particles hits
    '''

    def __init__(self, grid, deposit, cloud, readout):
        '''
        @brief default contructor
        @param grid : (PixelGrid) pixel matrix of interest
        @param deposit : (LandauDeposit) deposited charge by one particle
        @param cloud : (ChargeCloud) charge cloud generated by the particle
        @param readout : (Readout) detector readout, gives noise and threshold
        '''
        self.grid = grid
        self.deposit = deposit
        self.cloud = cloud
        self.readout = readout
    
    def digitize(self, hit0, hit1, hit_module, modules, rng):
        '''
        @brief Digitizes the hits of an event: charge, noisy pixels, noise, threshold
        @param hit0 : (np.array) local coordinate 0 of all hits, in mm
        @param hit1 : (np.array) local coordinate 1 of all hits, in mm
        @param hit_module : (np.array of uint64) geometry_id of the module of each hit
        @param modules : (np.array of uint64) modules where noisy pixels are generated
        @param rng : (numpy.random.Generator) generator of the event
        @return source, module, channel_0, channel_1, value : one entry per pixel readout. source is the index of the hit that lit the pixel, -1 for noise.
        '''
        
        source, channel_0, channel_1, value = self.cloud.share(self.grid, hit0, hit1, self.deposit.throw(len(hit0), rng))
        module = np.asarray(hit_module, dtype=np.uint64)[source]

        noise_module, noise_0, noise_1, noise_value = self.readout.noisy_pixels(modules, self.grid, rng)
        module = np.concatenate([module, noise_module])
        channel_0 = np.concatenate([channel_0, noise_0])
        channel_1 = np.concatenate([channel_1, noise_1])
        value = np.concatenate([value, noise_value])
        source = np.concatenate([source, np.full(len(noise_value), -1)])

        order = np.argsort(-value, kind="stable")
        module, channel_0, channel_1, value, source = (module[order], channel_0[order], channel_1[order], value[order], source[order])
        keys = np.column_stack([module, channel_0.astype(np.uint64), channel_1.astype(np.uint64)])
        _, first, inverse = np.unique(keys, axis=0, return_index=True, return_inverse=True)
        value = np.bincount(inverse.reshape(-1), weights=value)
        module, channel_0, channel_1, source = (module[first], channel_0[first], channel_1[first], source[first])

        value = self.readout.roll_noise(value, rng)
        fired = self.readout.above_threshold(value)
        return (source[fired], module[fired], channel_0[fired], channel_1[fired], value[fired])



        


         

        

    



    
